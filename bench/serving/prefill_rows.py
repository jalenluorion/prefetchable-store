#!/usr/bin/env python3
"""The prompt path's rows through the server, on a recorded OpenCode session (engine/results/agentic/replay/<session>/):
each main request is sent as the client sent it (not forced) with a short answer, which times its prompt (time to first
token) and the decode after it at that context; then the same request with the recorded answer forced (dm_force: the
server feeds it as the model's turn, so the next request finds the state a live session would have). The first request
is the cold prompt, the later ones the tool results and the new user turn. The server must run with --allow-force.

  prefill_rows.py SESSION_DIR OUT.jsonl --url URL [--decode 48] [--upto N] [--new-thread] [--long-tool FILE]

--new-thread: one request only, the session's first request with its user message replaced by a later user message of
the session (a new thread's first message: the system prompt from the prefix cache, the message prefilled)."""
import argparse, glob, json, os, time, urllib.request

ap = argparse.ArgumentParser()
ap.add_argument("session")
ap.add_argument("out")
ap.add_argument("--url", default="http://127.0.0.1:8092/v1")
ap.add_argument("--decode", type=int, default=48, help="tokens generated by the unforced request (its decode rate)")
ap.add_argument("--upto", type=int, default=0, help="the last request number to send (0: all)")
ap.add_argument("--new-thread", action="store_true")
ap.add_argument("--long-tool", default=None, help="after the session: its last request again with the last tool result replaced by this file's text (a long tool result)")
a = ap.parse_args()
recs = {r["n"]: r for r in (json.load(open(f)) for f in sorted(glob.glob(os.path.join(a.session, "[0-9][0-9][0-9].json"))))}
mains = [n for n in sorted(recs) if recs[n]["body"].get("tools") and (not a.upto or n <= a.upto)]
OUT = open(a.out, "a")


def send(body, tag, n, force=None, max_new=1):
    body = dict(body, stream=True, stream_options={"include_usage": True}, seed=1, max_tokens=max_new, temperature=0)
    body.pop("dm_force", None)
    if force:
        body["dm_force"] = force
    req = urllib.request.Request(a.url + "/chat/completions", data=json.dumps(body).encode(), headers={"Content-Type": "application/json"})
    t0 = time.time()
    first, last, usage, ntok = None, None, None, 0
    with urllib.request.urlopen(req, timeout=7200) as resp:
        for raw in resp:
            line = raw.decode(errors="replace").strip()
            if not line.startswith("data:"):
                continue
            d = line[5:].strip()
            if d == "[DONE]":
                break
            ch = json.loads(d)
            if ch.get("usage"):
                usage = ch["usage"]
            for c in ch.get("choices", []):
                dl = c.get("delta", {})
                if any(dl.get(k) for k in ("reasoning_content", "content", "tool_calls")):
                    if first is None:
                        first = time.time()
                    last = time.time()
    t1 = time.time()
    comp = (usage or {}).get("completion_tokens", 0)
    rec = {"tag": tag, "n": n, "forced": bool(force), "ttft_s": round(first - t0, 3) if first else None, "total_s": round(t1 - t0, 3),
           "prompt_tokens": (usage or {}).get("prompt_tokens"), "cached_tokens": ((usage or {}).get("prompt_tokens_details") or {}).get("cached_tokens"),
           "completion_tokens": comp, "decode_tok_s": round((comp - 1) / (t1 - first), 3) if first and comp > 1 and t1 > first else None, "t": round(t0, 3)}
    OUT.write(json.dumps(rec) + "\n")
    OUT.flush()
    print(json.dumps(rec), flush=True)


if a.new_thread:
    b = json.loads(json.dumps(recs[mains[0]]["body"]))
    later = [m for n in mains[1:] for m in recs[n]["body"]["messages"] if m.get("role") == "user"]
    first_user = next(i for i, m in enumerate(b["messages"]) if m.get("role") == "user")
    b["messages"] = b["messages"][: first_user] + [later[-1] if later else b["messages"][first_user]]
    send(b, "new_thread", mains[0], max_new=a.decode)
    raise SystemExit(0)
for i, n in enumerate(mains):
    send(recs[n]["body"], "cold" if i == 0 else "turn", n, max_new=a.decode)
    send(recs[n]["body"], "sync", n, force=recs[n]["answer"], max_new=1)
if a.long_tool:
    b = json.loads(json.dumps(recs[mains[-1]]["body"]))
    last_tool = max(i for i, m in enumerate(b["messages"]) if m.get("role") == "tool")
    b["messages"][last_tool]["content"] = open(a.long_tool).read()
    send(b, "long_tool", mains[-1], max_new=a.decode)
