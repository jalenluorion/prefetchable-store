"""The run defaults each family's published manifest declares, as the engine's fallback (src/core/published_defaults.inc).

  python3 python/convert/published_defaults.py [--check]      (python: the standard library only)

The engine resolves a run from the folder's moved-store.json; a key the folder's manifest leaves out (an older manifest
with no `profiles`, a folder with no manifest at all run with --profile) is taken from the published manifest of the
same family (python/convert/<family>/moved-store.json: the weight repo's as published), then from the engine's
family-neutral built-in values (src/core/presets.cpp). So no per-family value is written in the engine's code: this file
copies the declared keys (`modes`, `profiles` without their file lists, `defaults`, `drafting`) into a C++ string.
--check: exit 1 if the include differs from what the manifests give (tests/tiny_all.sh runs it).
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(REPO, "src", "core", "published_defaults.inc")
FAMILIES = sorted(d for d in os.listdir(HERE) if os.path.exists(os.path.join(HERE, d, "moved-store.json")))
# what a profile says about files and measurements, not about a run's settings (a folder's own record formats, `experts`,
# are read from that folder's manifest only)
DROP = {"parts", "bytes", "bytes_rule", "optional", "bytes_with_optional", "optional_note", "experts", "status", "when", "cache_rule",
        "precision", "precision_detail"}


def strip_notes(x):
    if isinstance(x, dict):
        return {k: strip_notes(v) for k, v in x.items() if k not in ("notes", "note", "definition", "measured_note")}
    if isinstance(x, list):
        return [strip_notes(v) for v in x]
    return x


out = {}
for f in FAMILIES:
    m = json.load(open(os.path.join(HERE, f, "moved-store.json")))
    e = {"modes": {k: {"engine": v["engine"]} for k, v in (m.get("modes") or {}).items() if "engine" in v},
         "profiles": {p: strip_notes({k: v for k, v in pv.items() if k not in DROP}) for p, pv in (m.get("profiles") or {}).items()},
         "defaults": strip_notes({k: v for k, v in (m.get("defaults") or {}).items() if k not in ("experts",)})}
    if "drafting" in m:
        e["drafting"] = {"cost_prior": m["drafting"].get("cost_prior")}
    out[f] = e
body = json.dumps(out, indent=1, sort_keys=True)
text = ("// Generated by python/convert/published_defaults.py from python/convert/<family>/moved-store.json: do not edit.\n"
        "// The run defaults each family's published manifest declares (the fallback for keys a folder's manifest leaves out).\n"
        'static const char* PUBLISHED_DEFAULTS = R"JSON(' + body + ')JSON";\n')
if "--check" in sys.argv:
    cur = open(OUT).read() if os.path.exists(OUT) else ""
    if cur != text:
        print(f"{OUT}: out of date (python3 python/convert/published_defaults.py)")
        sys.exit(1)
    print(f"{OUT}: current ({', '.join(FAMILIES)})")
else:
    open(OUT, "w").write(text)
    print(f"{OUT}: {', '.join(FAMILIES)}")
