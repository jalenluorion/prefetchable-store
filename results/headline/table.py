"""The README's measured numbers, generated from run records (never copied by hand).

  python3 results/headline/table.py                              print the tables
  python3 results/headline/table.py --write README.md            replace the block between the markers in README.md
  python3 results/headline/table.py --sync DIR [DIR ...] [--write README.md]
        first copy each DIR's decode and agent-turn records (*.json, *.ids) into results/headline/runs_final/, keeping only
        the fields the tables need; a later DIR replaces an earlier one's cell of the same name
  python3 results/headline/table.py --sync-prefill DIR [--write README.md]
        the same for a prefill timing folder (one worker process per model and rep: cold request, identical request,
        2,000-token append) into results/headline/runs_prefill/

Mac runs: one dmeng process each, greedy (--temp 0), --ctx 16384, --mem mlock, base M4 MacBook Pro 16 GB, internal SSD,
8 compute threads, 4 reader threads, each cell twice (the second time in reversed order). Names:
d_<model>_<prompt>_gb<G>_<cell>_r<rep> (decoding, 400 tokens; the large-cache cells of a campaign, b_..., are filed under d_)
and x_<model>_<case>_gb<G>_<cell>_r<rep> (agent turns). A run whose other processes used more than one core on average
(others' CPU above 100%) is left out (contaminated).

Phone rows: results/headline/phone.tsv (iPhone 15 Plus, measured on the device; one run per cell).
"""
import glob
import json
import os
import re
import shutil
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
RUNS = os.path.join(HERE, "runs_final")
PRE = os.path.join(HERE, "runs_prefill")
PHONE = os.path.join(HERE, "phone.tsv")
BEGIN, END = "<!-- headline tables: generated by results/headline/table.py -->", "<!-- end of generated tables -->"
MAX_OTHERS = 100.0  # others' CPU, % of one core: runs above it are left out
KEEP_GUARD = ("rc", "wall_s", "peak_footprint_gb_guard", "others_cpu_pct_mean")
KEEP = ("tok_s", "wait_ms_per_token", "compute_ms_per_token", "mb_read_per_token", "footprint_peak_gb", "accuracy", "tokens",
        "prompt_tokens", "cache_gb", "prefetch", "m", "prefill_s", "decode_steps", "hit_rate", "draft", "mode", "resolved")
MODELS = {"q36": "Qwen3.6-35B-A3B", "ink": "Inkling 2 Mini"}
DECODE = [("baseline", "base"), ("exact", "default"), ("fast", "dfast")]
AGENT = [("exact", "off"), ("exact, drafting on", "plain"), ("fast", "fast")]
PROMPTS = {"pitt": "prose", "code": "code"}
CASES = {"toolrw": "agent turn: file rewrite", "code": "code answer"}
# fast mode's measured agreement with exact (top choice equal; the model cards have the conditions)
AGREE = {("q36", "pitt"): "0.987", ("q36", "code"): "0.976", ("ink", "pitt"): "0.985", ("ink", "code"): "0.975"}


def slim(r):
    g = r.get("guard") or {}
    out = {k: r[k] for k in KEEP if k in r}
    if isinstance(out.get("resolved"), dict):  # the file names in it are machine paths: keep the router's name only
        rs = dict(out["resolved"])
        for k in ("routers", "cross_token"):
            if rs.get(k):
                rs[k] = os.path.basename(rs[k])
        out["resolved"] = rs
    out["guard"] = {k: g.get(k) for k in KEEP_GUARD if k in g}
    out["guard"]["power"] = [(g.get(w) or {}).get("power") for w in ("before", "after")]
    return out


def sync(srcs):
    os.makedirs(RUNS, exist_ok=True)
    for f in glob.glob(os.path.join(RUNS, "*")):
        os.remove(f)
    n = 0
    for src in srcs:
        for f in sorted(glob.glob(os.path.join(src, "*.json"))):
            name = os.path.basename(f)
            if not re.match(r"[bdx]_(q36|ink)_", name):
                continue
            name = "d" + name[1:] if name.startswith("b_") else name
            json.dump(slim(json.load(open(f))), open(os.path.join(RUNS, name), "w"), separators=(",", ":"))
            ids = f[:-5] + ".ids"
            if os.path.exists(ids):
                shutil.copyfile(ids, os.path.join(RUNS, name[:-5] + ".ids"))
            n += 1
    print(f"synced {n} runs from {', '.join(srcs)}", file=sys.stderr)


def sync_prefill(src):
    os.makedirs(PRE, exist_ok=True)
    for f in glob.glob(os.path.join(PRE, "*")):
        os.remove(f)
    for f in sorted(glob.glob(os.path.join(src, "*_r[0-9].json"))):
        n = os.path.basename(f)[:-5]
        log = open(os.path.join(src, n + ".log")).read()
        g = [l for l in log.splitlines() if l.startswith("GUARD ")]
        g = json.loads(g[-1][6:]) if g else {}
        ready = re.search(r'READY (\{.*\})', log)
        cache = json.loads(ready.group(1)).get("cache_gb") if ready else None
        reqs = [{"prompt_len": q["prompt_len"], "B": {k: (q.get("B") or {}).get(k) for k in ("reused", "computed", "source", "ms_prefill")},
                 "ms_first_token": ((q.get("E") or {}).get("json") or {}).get("ms_first_token")} for q in json.load(open(f))]
        json.dump({"cache_gb": cache, "requests": reqs, "guard": {"others_cpu_pct_mean": g.get("others_cpu_pct_mean"),
                   "peak_footprint_gb_guard": g.get("peak_footprint_gb_guard"),
                   "power": [(g.get(w) or {}).get("power") for w in ("before", "after")]}},
                  open(os.path.join(PRE, n + ".json"), "w"), separators=(",", ":"))
    print(f"synced the prefill runs of {src}", file=sys.stderr)


def load():
    cells = defaultdict(dict)  # name without _rN -> {rep: (json, ids)}
    for f in sorted(glob.glob(os.path.join(RUNS, "*.json"))):
        m = re.match(r"(.+)_r(\d+)\.json$", os.path.basename(f))
        if not m:
            continue
        ids = f[:-5] + ".ids"
        cells[m.group(1)][int(m.group(2))] = (json.load(open(f)), open(ids).read().strip() if os.path.exists(ids) else None)
    return cells


def clean(c):
    """the runs of a cell that count: finished, others' CPU at most MAX_OTHERS"""
    out = []
    for rep in sorted(c or {}):
        r = c[rep][0]
        g = r.get("guard") or {}
        if g.get("rc", 0) == 0 and (g.get("others_cpu_pct_mean") or 0) <= MAX_OTHERS and r.get("tok_s"):
            out.append(c[rep])
    return out


def rng(v, fmt="%.1f"):
    if not v:
        return "-"
    lo, hi = fmt % min(v), fmt % max(v)
    return lo if lo == hi else f"{lo}-{hi}"


def rate(c):
    """tok/s of the clean runs: a range over the reps, '(1 run)' when one counts; '-' none measured"""
    runs = clean(c)
    if not runs:
        return "-" if not c else "- (contaminated)"
    return rng([r["tok_s"] for r, _ in runs]) + (" (1 run)" if len(runs) == 1 and len(c) > 1 else "")


def col(cs, key):
    return [r.get(key) or 0 for c in cs for r, _ in clean(c)]


def power(cs):
    p = {("battery" if any(x and "Battery" in x for x in (r.get("guard") or {}).get("power") or []) else "AC") for c in cs for r, _ in clean(c)}
    return "/".join(sorted(p)) or "-"


def others(cs):
    o = [(r.get("guard") or {}).get("others_cpu_pct_mean") or 0 for c in cs for r, _ in clean(c)]
    return (rng(o, "%d") + "%") if o else ""


def ids_note(cs):
    """exact runs: every clean run of the row must give the same greedy ids (a shorter run a prefix of a longer one)"""
    seqs = [ids.split(",") for c in cs for r, ids in clean(c) if ids and r.get("accuracy", "lossless") == "lossless"]
    if len(seqs) < 2:
        return ""
    ref = max(seqs, key=len)
    return "identical" if all(s == ref[: len(s)] for s in seqs) else "DIFFER"


def sizes(cells, tag, m):
    return sorted({float(re.search(r"_gb([\d.]+)_", k).group(1)) for k in cells if k.startswith(f"{tag}_{m}_")})


def decode_table(cells, m):
    out = ["| cache GB | prompt | baseline | exact | fast | fast: agreement with exact | peak footprint GB | power | others' CPU | exact ids |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for gb in sizes(cells, "d", m):
        for p in PROMPTS:
            cs = [cells.get(f"d_{m}_{p}_gb{gb:g}_{k}") or cells.get(f"d_{m}_{p}_gb{gb}_{k}") for _, k in DECODE]
            if not any(cs):
                continue
            pt = next((r.get("prompt_tokens") for c in cs for r, _ in clean(c) if r.get("prompt_tokens")), None)
            label = PROMPTS[p] + (f" ({pt}-token prompt)" if pt else "")
            out.append(f"| {gb:g} | {label} | " + " | ".join(rate(c) for c in cs) + f" | {AGREE[(m, p)]} | {rng(col(cs, 'footprint_peak_gb'))} | "
                       f"{power(cs)} | {others(cs)} | {ids_note(cs[1:2])} |")
    return out if len(out) > 2 else []


def agent_table(cells, m):
    out = ["| turn | cache GB | " + " | ".join(h for h, _ in AGENT) + " | tokens per pass, drafting on | peak footprint GB | power | others' CPU |",
           "|---|---|" + "---|" * len(AGENT) + "---|---|---|---|"]
    for case in CASES:
        for gb in sizes(cells, "x", m):
            cs = [cells.get(f"x_{m}_{case}_gb{gb:g}_{k}") or cells.get(f"x_{m}_{case}_gb{gb}_{k}") for _, k in AGENT]
            if not any(cs):
                continue
            pt = next((r.get("prompt_tokens") for c in cs for r, _ in clean(c) if r.get("prompt_tokens")), None)
            label = CASES[case] + (f" ({pt}-token prompt)" if pt else "")
            tps = [((r.get("draft") or {}).get("tokens_per_step") or 0) for r, _ in clean(cs[1])] if cs[1] else []
            out.append(f"| {label} | {gb:g} | " + " | ".join(rate(c) for c in cs) + f" | {rng(tps, '%.2f')} | {rng(col(cs, 'footprint_peak_gb'))} | "
                       f"{power(cs)} | {others(cs)} |")
    return out if len(out) > 2 else []


def prefill_table():
    runs = defaultdict(list)
    for f in sorted(glob.glob(os.path.join(PRE, "*.json"))):
        runs[os.path.basename(f).split("_r")[0]].append(json.load(open(f)))
    if not runs:
        return []
    out = ["| model | cache GB | request | prompt tokens | computed | reused (from) | seconds to first token | s per 1,000 computed | peak footprint GB | power | others' CPU |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for m in ("q36", "ink"):
        rs = runs.get(m) or []
        for k, name in enumerate(("cold", "identical request again", "2,000-token append")):
            q = [r["requests"][k] for r in rs if len(r["requests"]) > k]
            if not q:
                continue
            b = q[0]["B"]
            ttft = [x["ms_first_token"] / 1e3 for x in q]
            per = [1000 * x["B"]["ms_prefill"] / 1e3 / x["B"]["computed"] for x in q if x["B"]["computed"]]
            g = [r["guard"] for r in rs]
            pw = "/".join(sorted({"battery" if any(p and "Battery" in p for p in x["power"]) else "AC" for x in g}))
            out.append(f"| {MODELS[m]} | {rs[0]['cache_gb']:g} | {name} | {q[0]['prompt_len']:,} | {b['computed']:,} | {b['reused']:,} ({b['source']}) | "
                       f"{rng(ttft)} | {rng(per)} | {rng([x['peak_footprint_gb_guard'] for x in g])} | {pw} | "
                       f"{rng([x['others_cpu_pct_mean'] or 0 for x in g], '%d')}% |")
    return out


def phone_table():
    if not os.path.exists(PHONE):
        return []
    rows = [l.split("\t") for l in open(PHONE).read().splitlines() if l and not l.startswith("#")]
    out = ["| " + " | ".join(rows[0]) + " |", "|" + "---|" * len(rows[0])]
    return out + ["| " + " | ".join(r) + " |" for r in rows[1:]]


def tables():
    cells = load()
    L = [BEGIN, ""]
    for m in MODELS:
        t = decode_table(cells, m)
        L += [f"**{MODELS[m]}, decoding** (400 tokens after the prompt; tokens/s, range over two runs)", ""]
        L += t or ["(no runs yet)"]
        L += [""]
        t = agent_table(cells, m)
        if t:
            L += [f"**{MODELS[m]}, agent turns** (recorded agent prompts, prefill then generation to the end of the turn; one run per cell)", ""]
            L += t + [""]
    t = prefill_table()
    if t:
        L += ["**Prompt prefill through the server** (`dmserve` at the `mac` defaults with a fixed cache; the recorded long agent "
              "request of each model, then the same request again, then 2,000 more tokens; one run per row)", ""] + t + [""]
    t = phone_table()
    if t:
        L += ["**iPhone 15 Plus** (`phone-small` profile, measured on the device)", ""] + t + [""]
    L += ["Mac: base M4 MacBook Pro, 16 GB, internal SSD, 8 compute threads, `--mem mlock`, greedy decoding. Baseline: no "
          "router names, the frequency eviction rule (`--prefetch none --evict freq --layer-caps none`), no run-ahead. Exact: the "
          "`mac` profile's defaults, nothing passed; its tokens never depend on the cache, the routers or timing. Fast: the same "
          "with `--mode fast`; its tokens can differ from exact, and the agreement column gives how often its top choice equals "
          "exact's. A run is left out when other processes used more than one core on average (contaminated); a cell with one "
          "run left is marked. Exact ids: the greedy ids of the row's exact runs compared with each other.", "", END]
    return "\n".join(L)


if __name__ == "__main__":
    a = sys.argv[1:]
    if "--sync" in a:
        i = a.index("--sync") + 1
        srcs = []
        while i < len(a) and not a[i].startswith("--"):
            srcs.append(a[i])
            i += 1
        sync(srcs)
    if "--sync-prefill" in a:
        sync_prefill(a[a.index("--sync-prefill") + 1])
    t = tables()
    if "--write" in a:
        p = a[a.index("--write") + 1]
        s = open(p).read()
        i, j = s.index(BEGIN), s.index(END) + len(END)
        open(p, "w").write(s[:i] + t + s[j:])
        print(f"wrote the tables into {p}", file=sys.stderr)
    else:
        print(t)
