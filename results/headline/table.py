"""The README's measured numbers, generated from run records (never copied by hand).

  python3 results/headline/table.py                              print the tables
  python3 results/headline/table.py --write README.md            replace the block between the markers in README.md
  python3 results/headline/table.py --sync DIR [--write README.md]
        first copy DIR/*.json and *.ids (a campaign's output folder) into results/headline/runs_final/, keeping only the
        fields the tables need (the guard block: others' CPU, footprint, power source)

Mac runs (results/headline/runs_final/): one dmeng process each, greedy (--temp 0), --ctx 16384, --mem mlock, base M4
MacBook Pro 16 GB, internal SSD, 8 compute threads, 4 reader threads, each cell twice (the second time in reversed
order). Names: d_<model>_<prompt>_gb<G>_<cell>_r<rep> (decoding, 400 tokens) and x_<model>_<case>_gb<G>_<cell>_r<rep>
(agent turns). A run whose other processes used more than one core on average (others' CPU above 100%) is left out.

Phone rows: the side-by-side table of results/ios/p2/P2.md (iPhone 15 Plus, the phone-small profile: 4-bit in-memory
weights), read as written there.
"""
import glob
import json
import os
import re
import shutil
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
RUNS = os.path.join(HERE, "runs_final")
P2 = os.path.join(REPO, "results", "ios", "p2", "P2.md")
BEGIN, END = "<!-- headline tables: generated by results/headline/table.py -->", "<!-- end of generated tables -->"
MAX_OTHERS = 100.0  # others' CPU, % of one core: runs above it are left out
KEEP_GUARD = ("rc", "wall_s", "peak_footprint_gb_guard", "peak_swap_growth_mb", "swap_growth_end_mb", "others_cpu_pct_mean")
KEEP = ("tok_s", "wait_ms_per_token", "compute_ms_per_token", "mb_read_per_token", "footprint_peak_gb", "accuracy", "tokens",
        "prompt_tokens", "cache_gb", "prefetch", "m", "prefill_s", "decode_steps", "hit_rate", "draft")
MODELS = {"q36": "Qwen3.6-35B-A3B", "ink": "Inkling 2 Mini"}
# the decode cells: cache only (no names, the older eviction), exact (the default routers), fast (approx:drop)
DECODE = {"q36": [("cache only", "cache"), ("exact", "ours_lin"), ("fast", "fast")],
          "ink": [("cache only", "cache"), ("exact", "ours"), ("fast", "fast")]}
AGENT = [("exact, with names", "off"), ("exact, no names", "nonames"), ("fast", "fast")]
PROMPTS = {"pitt": "prose", "code": "code"}
CASES = {"toolrw": "agent turn: file rewrite", "toolnew": "agent turn: new file", "code": "code answer"}


def sync(src):
    os.makedirs(RUNS, exist_ok=True)
    n = 0
    for f in sorted(glob.glob(os.path.join(src, "*.json"))):
        r = json.load(open(f))
        g = r.get("guard") or {}
        out = {k: r[k] for k in KEEP if k in r}
        out["guard"] = {k: g.get(k) for k in KEEP_GUARD if k in g}
        out["guard"]["power"] = [(g.get(w) or {}).get("power") for w in ("before", "after")]
        json.dump(out, open(os.path.join(RUNS, os.path.basename(f)), "w"), separators=(",", ":"))
        ids = f[:-5] + ".ids"
        if os.path.exists(ids):
            shutil.copyfile(ids, os.path.join(RUNS, os.path.basename(ids)))
        n += 1
    print(f"synced {n} runs from {src}", file=sys.stderr)


def load():
    cells = defaultdict(dict)  # name without _rN -> {rep: (json, ids)}
    for f in sorted(glob.glob(os.path.join(RUNS, "*.json"))):
        m = re.match(r"(.+)_r(\d+)\.json$", os.path.basename(f))
        if not m:
            continue
        ids = f[:-5] + ".ids"
        cells[m.group(1)][int(m.group(2))] = (json.load(open(f)), open(ids).read().strip() if os.path.exists(ids) else None)
    return cells


def clean(c):
    """the runs of a cell that count: finished, others' CPU at most MAX_OTHERS"""
    out = []
    for rep in sorted(c or {}):
        r = c[rep][0]
        g = r.get("guard") or {}
        if g.get("rc", 0) == 0 and (g.get("others_cpu_pct_mean") or 0) <= MAX_OTHERS and r.get("tok_s"):
            out.append(c[rep])
    return out


def rate(c):
    """tok/s of the clean runs: 'a / b' (both) or 'a (one clean run)'; '-' none; '*' = on battery"""
    runs = clean(c)
    if not runs:
        return "-" if not c else "- (no clean run)"
    v = []
    for r, _ in runs:
        bat = any(x and "Battery" in x for x in (r.get("guard") or {}).get("power") or [])
        v.append("%.1f%s" % (r["tok_s"], "*" if bat else ""))
    return " / ".join(v) + (" (one clean run)" if len(v) == 1 else "")


def others(cs):
    o = [(r.get("guard") or {}).get("others_cpu_pct_mean") or 0 for c in cs for r, _ in clean(c)]
    if not o:
        return ""
    return "%d%%" % min(o) if int(min(o)) == int(max(o)) else "%d-%d%%" % (min(o), max(o))


def footprint(cs):
    f = [r.get("footprint_peak_gb") or 0 for c in cs for r, _ in clean(c)]
    if not f:
        return ""
    lo, hi = "%.1f" % min(f), "%.1f" % max(f)
    return lo if lo == hi else f"{lo}-{hi}"


def ids_note(cs):
    """exact runs (lossless): every clean run must give the same greedy ids (a shorter run a prefix of a longer one)"""
    seqs = [ids.split(",") for c in cs for r, ids in clean(c) if ids and r.get("accuracy", "lossless") == "lossless"]
    if len(seqs) < 2:
        return ""
    ref = max(seqs, key=len)
    return "identical" if all(s == ref[: len(s)] for s in seqs) else "DIFFER"


def sizes(cells, tag, m):
    return sorted({float(re.search(r"_gb([\d.]+)_", k).group(1)) for k in cells if k.startswith(f"{tag}_{m}_")})


def first(cs, key):
    for c in cs:
        for r, _ in clean(c):
            if r.get(key) is not None:
                return r[key]
    return None


def decode_table(cells, m):
    cols = DECODE[m]
    out = ["| cache GB | prompt | " + " | ".join(h for h, _ in cols) + " | peak footprint GB | others' CPU | exact ids |",
           "|---|---|" + "---|" * len(cols) + "---|---|---|"]
    rows = 0
    for gb in sizes(cells, "d", m):
        for p in PROMPTS:
            cs = [cells.get(f"d_{m}_{p}_gb{gb}_{k}") for _, k in cols]
            if not any(cs):
                continue
            pt = first(cs, "prompt_tokens")
            label = PROMPTS[p] + (f" ({pt}-token prompt)" if pt else "")
            out.append(f"| {gb:g} | {label} | " + " | ".join(rate(c) for c in cs) + f" | {footprint(cs)} | {others(cs)} | {ids_note(cs)} |")
            rows += 1
    return out if rows else []


def agent_table(cells, m):
    out = ["| turn | cache GB | " + " | ".join(h for h, _ in AGENT) + " | peak footprint GB | others' CPU | exact ids |",
           "|---|---|" + "---|" * len(AGENT) + "---|---|---|"]
    rows = 0
    for case in CASES:
        for gb in sizes(cells, "x", m):
            cs = [cells.get(f"x_{m}_{case}_gb{gb}_{k}") for _, k in AGENT]
            if not any(cs):
                continue
            pt = first(cs, "prompt_tokens")
            label = CASES[case] + (f" ({pt}-token prompt)" if pt else "")
            out.append(f"| {label} | {gb:g} | " + " | ".join(rate(c) for c in cs) + f" | {footprint(cs)} | {others(cs)} | {ids_note(cs)} |")
            rows += 1
    return out if rows else []


def phone_table():
    """old app / exact / fast on the iPhone 15 Plus, from the side-by-side table of P2.md"""
    if not os.path.exists(P2):
        return []
    lines = open(P2).read().splitlines()
    try:
        i = next(k for k, l in enumerate(lines) if l.startswith("### Side by side") and "4-bit" in l)
    except StopIteration:
        return []
    date = re.search(r"\((?:phone, )?(\d{4}-\d{2}-\d{2})", lines[i])
    date = date.group(1) if date else ""
    tab = []
    for l in lines[i + 1:]:
        if l.startswith("|"):
            tab.append([x.strip() for x in l.strip("|").split("|")])
        elif tab:
            break
    head, body = tab[0], tab[2:]
    col = lambda name: next(k for k, h in enumerate(head) if h.startswith(name))
    c_old, c_exact, c_fast = col("old engine"), col("4-bit lossless"), col("4-bit approx:drop")
    want = ("decode, Pittsburgh", "decode, coding", "first token", "follow-up", "same chat after a relaunch", "cold launch")
    short = lambda s: re.sub(r"\s*\([^()]{40,}\)", "", s.replace("**", "").replace("today", ("on " + date) if date else "today")).strip() or "-"
    out = [f"| aspect | old app | exact | fast |", "|---|---|---|---|"]
    for r in body:
        if not r[0].startswith(want):
            continue
        aspect = r[0] + (f" (as of {date})" if r[0].startswith(("first token", "follow-up", "same chat")) and date else "")
        out.append(f"| {aspect} | {short(r[c_old])} | {short(r[c_exact])} | {short(r[c_fast])} |")
    return out


def tables():
    cells = load()
    L = [BEGIN, ""]
    for m in MODELS:
        t = decode_table(cells, m)
        L += [f"**{MODELS[m]}, decoding** (400 tokens after the prompt, MacBook Pro M4 16 GB; tokens/s of each clean run)", ""]
        L += t or ["(no clean runs yet)"]
        L += [""]
        t = agent_table(cells, m)
        L += [f"**{MODELS[m]}, agent turns** (recorded agent prompts, batched prompt prefill, generation to the end of the turn)", ""]
        L += t or ["(no clean runs yet)"]
        L += [""]
    t = phone_table()
    if t:
        L += ["**Qwen3.6-35B-A3B on an iPhone 15 Plus** (phone-small profile: 4-bit in-memory weights; one run per cell; "
              "the old app is the earlier MLX-based app on the same phone)", ""] + t + [""]
    L += ["Cache only: no names and the older eviction rule (`--evict freq`). Exact: the profile's routers (35B: `linear_k2`, "
          "top 8; Inkling: `mlp_k2_h512` with the confidence rule and cross-token names). Fast: `--mode fast`. Two numbers "
          "are the two repetitions; a run is left out when other processes used more than one core on average "
          "(others' CPU above 100%), and a cell with one run left is marked. `*`: on battery. Exact ids: the greedy ids of "
          "the row's exact runs compared with each other.", "", END]
    return "\n".join(L)


if __name__ == "__main__":
    a = sys.argv[1:]
    if "--sync" in a:
        sync(a[a.index("--sync") + 1])
    t = tables()
    if "--write" in a:
        p = a[a.index("--write") + 1]
        s = open(p).read()
        i, j = s.index(BEGIN), s.index(END) + len(END)
        open(p, "w").write(s[:i] + t + s[j:])
        print(f"wrote the tables into {p}", file=sys.stderr)
    else:
        print(t)
